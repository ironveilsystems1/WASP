#!/usr/bin/env bash
# =============================================================================
# test-remoteip-fix.sh — wp-hardening.sh remoteip-fix, the 10.15 repair
# =============================================================================
#
# A VM built by 10.14 or earlier declares its reverse proxy to mod_remoteip as
# RemoteIPTrustedProxy, in TWO mounted files. That discards a private client
# address, so an administrator arriving from the LAN or over NetBird is seen as
# the proxy and refused at wp-admin. `remoteip-fix` rewrites the declaration to
# RemoteIPInternalProxy <one address> and masks the second file.
#
# The real tool is run against files shaped like a 10.14 VM, with a stand-in
# podman that answers configtest as told and reports, for the "live" check, the
# directives in the files the container would mount. Asserted:
#
#   - --check reports and changes nothing
#   - the repair rewrites IN PLACE (same inode: the files are bind-mounted, and
#     a replaced inode is invisible to the running container)
#   - everything else in wp-security.conf is untouched
#   - a failed configtest restores both files byte for byte and restarts nothing
#   - a range, a list, an unexpected proxy, or no declaration at all is refused
#   - an already-repaired VM (including the hand fix applied in the field) is
#     left alone and not restarted
#
# Run under the build host's /bin/sh and again under BusyBox, which is what
# Alpine has. BusyBox is required: set BUSYBOX=/path/to/busybox.
# =============================================================================
set -u
REPO="$(cd "$(dirname "$0")/.." && pwd)"
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
PASS=0; FAIL=0
_p() { PASS=$((PASS+1)); printf '  [PASS] %s\n' "$1"; }
_f() { FAIL=$((FAIL+1)); printf '  [FAIL] %s\n         %s\n' "$1" "${2:-}"; }
TOOL="$REPO/payload/bin/wp-hardening.sh"

echo ""
echo "wp-hardening.sh remoteip-fix (mod_remoteip declaration repair)"

if [ "$(id -u)" -ne 0 ]; then
  _f "must run as root" "wp-hardening.sh re-executes through doas otherwise"
  echo "  remoteip-fix: ${PASS} passed, ${FAIL} failed"; exit 1
fi

BB="${BUSYBOX:-$(command -v busybox 2>/dev/null || true)}"

# The 10.14 shape of the two files, with content around the directive that
# must survive the rewrite.
_legacy_sec() {
  cat <<'EOF'
# Generated by WASP — Apache security configuration
LoadModule remoteip_module /usr/lib/apache2/modules/mod_remoteip.so
RemoteIPHeader X-Forwarded-For
RemoteIPTrustedProxy 10.20.10.10

<DirectoryMatch "^/var/www/html/wp-admin">
    <RequireAll>
        Require not ip 10.20.10.10
        <RequireAny>
            Require ip 10.20.1.0/24
        </RequireAny>
    </RequireAll>
</DirectoryMatch>
Header always set X-Frame-Options "SAMEORIGIN"
EOF
}
_legacy_mask() { printf 'RemoteIPHeader X-Forwarded-For\nRemoteIPTrustedProxy 10.20.10.10\n'; }

_run_suite() { # label, shell, PATH prefix dir
  local L="$1" SH="$2" PP="$3"
  local W="$T/$L"; mkdir -p "$W/bin"
  # Stand-in podman. configtest obeys $W/ct (ok|fail); the live check reports
  # the directives in the files Apache would load: the mounted files, $W/extra,
  # and $W/img -- the image's own conf-enabled/remoteip.conf, present only
  # while it is enabled (rm disables it, the a2enconf link puts it back).
  cat > "$W/bin/podman" <<STUB
#!$SH
case "\$*" in
  *configtest*) [ "\$(cat "$W/ct")" = ok ] && { echo 'Syntax OK'; exit 0; }
                echo 'AH00526: Syntax error on line 4'; exit 1 ;;
  'restart wordpress') echo restart >> "$W/restarts"; echo wordpress; exit 0 ;;
  *'test -s /etc/apache2/conf-enabled/remoteip.conf') [ -s "$W/img" ]; exit \$? ;;
  *'rm -f /etc/apache2/conf-enabled/remoteip.conf') [ -f "$W/rmfail" ] && exit 1; rm -f "$W/img"; exit 0 ;;
  *'ln -s ../conf-available/remoteip.conf'*) cp "$W/img.orig" "$W/img"; exit 0 ;;
  *RemoteIP*) grep -hE '^[[:space:]]*RemoteIP(Internal|Trusted)Proxy[[:space:]]' \
                "$W/wp-security.conf" "$W/remoteip.conf" "$W/extra" "$W/img" 2>/dev/null; exit 0 ;;
esac
exit 0
STUB
  chmod +x "$W/bin/podman"
  # Default: a VM provisioned from 10.6 -- the image's file masked by a mount
  # recorded in wp-run-extra.env.
  _reset() { _legacy_sec > "$W/wp-security.conf"; _legacy_mask > "$W/remoteip.conf"
             echo ok > "$W/ct"; : > "$W/extra"; rm -f "$W/restarts" "$W/img" "$W/img.orig" "$W/rmfail"
             : > "$W/imask"
             printf "WP_EXTRA_VOLS='-v /home/wpuser/wp/secrets:/var/www/private:ro -v %s:/etc/apache2/conf-enabled/remoteip.conf:ro'\n" \
               "$W/imask" > "$W/env"; }
  _fix() { # args...
    env PATH="$W/bin:$PP" PROXY_IP="${RF_PROXY-10.20.10.10}" \
        WASP_RF_SEC="$W/wp-security.conf" WASP_RF_MASK="$W/remoteip.conf" \
        WASP_RF_ENV="$W/env" WASP_RF_IMGMASK="$W/imask" \
        "$SH" "$TOOL" remoteip-fix "$@" 2>&1; }
  _restarts() { [ -f "$W/restarts" ] && wc -l < "$W/restarts" | tr -d ' ' || echo 0; }

  echo ""
  echo "  ── under ${L}"

  _reset; cp "$W/wp-security.conf" "$W/sec.orig"; cp "$W/remoteip.conf" "$W/mask.orig"
  out=$(_fix --check); rc=$?
  [ "$rc" = 1 ] && printf '%s' "$out" | grep -q 'remoteip-fix' \
    && _p "$L: --check on a 10.14 VM exits 1 and names the repair" \
    || _f "$L: --check did not report the 10.14 shape" "rc=$rc out=$out"
  cmp -s "$W/wp-security.conf" "$W/sec.orig" && cmp -s "$W/remoteip.conf" "$W/mask.orig" \
    && [ "$(_restarts)" = 0 ] \
    && _p "$L: --check changes nothing and restarts nothing" \
    || _f "$L: --check modified the VM" ""

  _reset; ino=$(ls -i "$W/wp-security.conf" | awk '{print $1}')
  mino=$(ls -i "$W/remoteip.conf" | awk '{print $1}')
  out=$(_fix); rc=$?
  [ "$rc" = 0 ] && _p "$L: repair exits 0" || _f "$L: repair failed" "rc=$rc out=$out"
  grep -qx 'RemoteIPInternalProxy 10.20.10.10' "$W/wp-security.conf" \
    && ! grep -q 'RemoteIPTrustedProxy' "$W/wp-security.conf" \
    && _p "$L: wp-security.conf now declares RemoteIPInternalProxy 10.20.10.10" \
    || _f "$L: the declaration was not rewritten" "$(cat "$W/wp-security.conf")"
  ! grep -qE '^[[:space:]]*RemoteIP' "$W/remoteip.conf" && grep -q '^# masked' "$W/remoteip.conf" \
    && _p "$L: the mods-enabled file is a directive-free mask" \
    || _f "$L: the second declaration survived" "$(cat "$W/remoteip.conf")"
  [ "$(ls -i "$W/wp-security.conf" | awk '{print $1}')" = "$ino" ] \
    && [ "$(ls -i "$W/remoteip.conf" | awk '{print $1}')" = "$mino" ] \
    && _p "$L: both files rewritten in place (inode kept; they are bind-mounted)" \
    || _f "$L: a file's inode changed" "the running container would keep reading the old file"
  diff <(grep -v 'RemoteIP.*Proxy' "$W/sec.orig") <(grep -v 'RemoteIP.*Proxy' "$W/wp-security.conf") >/dev/null \
    && _p "$L: nothing else in wp-security.conf changed" \
    || _f "$L: other lines were altered" "$(diff "$W/sec.orig" "$W/wp-security.conf")"
  [ "$(_restarts)" = 1 ] && _p "$L: WordPress restarted once" || _f "$L: restart count $(_restarts)" ""
  printf '%s' "$out" | grep -q 'exactly one declaration' \
    && _p "$L: the live check confirms one declaration" \
    || _f "$L: the live check did not confirm" "$out"

  rm -f "$W/restarts"; out=$(_fix); rc=$?
  [ "$rc" = 0 ] && printf '%s' "$out" | grep -q 'Nothing to repair' && [ "$(_restarts)" = 0 ] \
    && _p "$L: a second run is a no-op and does not restart" \
    || _f "$L: not idempotent" "rc=$rc restarts=$(_restarts) out=$out"

  # The hand fix applied in the field to WP02/WP03.
  _reset; printf '# masked: mod_remoteip is configured in conf-enabled/wp-security.conf\n' > "$W/remoteip.conf"
  sed 's/^RemoteIPTrustedProxy /RemoteIPInternalProxy /' "$W/sec.orig" > "$W/wp-security.conf"
  out=$(_fix); rc=$?
  [ "$rc" = 0 ] && printf '%s' "$out" | grep -q 'Nothing to repair' && [ "$(_restarts)" = 0 ] \
    && _p "$L: a VM fixed by hand in the field is recognised and left alone" \
    || _f "$L: the field fix was not recognised" "rc=$rc out=$out"

  # Only the second file still declares the proxy.
  _reset; sed 's/^RemoteIPTrustedProxy /RemoteIPInternalProxy /' "$W/sec.orig" > "$W/wp-security.conf"
  out=$(_fix); rc=$?
  [ "$rc" = 0 ] && ! grep -qE '^[[:space:]]*RemoteIP' "$W/remoteip.conf" \
    && _p "$L: a half-done fix (second file still live) is completed" \
    || _f "$L: the second file was not masked" "rc=$rc $(cat "$W/remoteip.conf")"

  _reset; echo fail > "$W/ct"; out=$(_fix); rc=$?
  [ "$rc" = 1 ] && cmp -s "$W/wp-security.conf" "$W/sec.orig" && cmp -s "$W/remoteip.conf" "$W/mask.orig" \
    && _p "$L: a failed configtest restores both files byte for byte" \
    || _f "$L: a failed configtest left the files changed" "rc=$rc"
  [ "$(_restarts)" = 0 ] && _p "$L: ...and restarts nothing" || _f "$L: restarted after a failed configtest" ""

  _reset; sed 's/^RemoteIPTrustedProxy 10.20.10.10$/RemoteIPTrustedProxy 10.20.10.0\/24/' "$W/sec.orig" > "$W/wp-security.conf"
  cp "$W/wp-security.conf" "$W/sec.range"; out=$(_fix); rc=$?
  [ "$rc" = 1 ] && cmp -s "$W/wp-security.conf" "$W/sec.range" \
    && _p "$L: a range already in wp-security.conf is refused, not rewritten" \
    || _f "$L: a range was rewritten or accepted" "rc=$rc $(grep RemoteIP "$W/wp-security.conf")"

  _reset; printf 'RemoteIPInternalProxy 10.0.0.0/8\n' >> "$W/wp-security.conf"; out=$(_fix); rc=$?
  [ "$rc" = 1 ] && printf '%s' "$out" | grep -q 'other than' \
    && _p "$L: an extra hand-added proxy declaration is refused" \
    || _f "$L: an unexpected declaration was tolerated" "rc=$rc out=$out"

  _reset; grep -v 'RemoteIP.*Proxy' "$W/sec.orig" > "$W/wp-security.conf"; out=$(_fix); rc=$?
  [ "$rc" = 1 ] && printf '%s' "$out" | grep -q 'no mod_remoteip proxy declaration' \
    && _p "$L: a wp-security.conf with no declaration is refused" \
    || _f "$L: a missing declaration was not reported" "rc=$rc out=$out"

  _reset; out=$(RF_PROXY=10.20.10.0/24 _fix); rc=$?
  [ "$rc" = 1 ] && cmp -s "$W/wp-security.conf" "$W/sec.orig" \
    && _p "$L: PROXY_IP as a range is refused" || _f "$L: a range PROXY_IP was used" "rc=$rc"
  _reset; out=$(RF_PROXY='10.20.10.10,10.20.10.11' _fix); rc=$?
  [ "$rc" = 1 ] && _p "$L: PROXY_IP as a list is refused" || _f "$L: a list PROXY_IP was used" "rc=$rc"
  _reset; out=$(RF_PROXY= _fix); rc=$?
  [ "$rc" = 0 ] && cmp -s "$W/wp-security.conf" "$W/sec.orig" \
    && _p "$L: no PROXY_IP: nothing to do, nothing changed" || _f "$L: acted with no proxy configured" "rc=$rc"

  # The container still reads a declaration the files no longer carry (e.g. a
  # mount the repair cannot see): reported, not passed.
  _reset; printf 'RemoteIPTrustedProxy 10.20.10.10\n' > "$W/extra"; out=$(_fix); rc=$?
  [ "$rc" = 1 ] && printf '%s' "$out" | grep -q 'Expected exactly' \
    && _p "$L: a stray live declaration in the container fails the repair" \
    || _f "$L: a stray live declaration was not caught" "rc=$rc out=$out"

  # ── A VM provisioned before 10.6 (found on a 10.4 VM upgraded to 10.20) ──
  # The two files already in the 10.15 form, but the image's own remoteip.conf
  # is live and wp-run-extra.env has no mount masking it.
  _pre106() {
    _reset
    sed 's/^RemoteIPTrustedProxy /RemoteIPInternalProxy /' "$W/sec.orig" > "$W/wp-security.conf"
    printf '# masked: mod_remoteip is configured in conf-enabled/wp-security.conf\n' > "$W/remoteip.conf"
    printf "WP_EXTRA_VOLS='-v /home/wpuser/wp/secrets:/var/www/private:ro'\n" > "$W/env"
    rm -f "$W/imask"
    printf 'RemoteIPHeader X-Forwarded-For\nRemoteIPInternalProxy 10.0.0.0/8\nRemoteIPInternalProxy 172.16.0.0/12\nRemoteIPInternalProxy 192.168.0.0/16\n' > "$W/img"
    cp "$W/img" "$W/img.orig"; cp "$W/env" "$W/env.orig"
  }
  _mlines() { grep -cF "$W/imask:/etc/apache2/conf-enabled/remoteip.conf:ro" "$W/env"; }

  _pre106; out=$(_fix --check); rc=$?
  [ "$rc" = 1 ] && printf '%s' "$out" | grep -q "image's own" && printf '%s' "$out" | grep -q 'returns on every rebuild' \
    && _p "$L: pre-10.6: --check reports the image's live remoteip.conf and the missing mount" \
    || _f "$L: pre-10.6: --check passed a VM Apache still reads 10/8 on" "rc=$rc out=$out"
  cmp -s "$W/env" "$W/env.orig" && [ -s "$W/img" ] && [ ! -e "$W/imask" ] && [ "$(_restarts)" = 0 ] \
    && _p "$L: pre-10.6: --check changes nothing" || _f "$L: pre-10.6: --check modified the VM" ""

  _pre106; out=$(_fix); rc=$?
  [ "$rc" = 0 ] && printf '%s' "$out" | grep -q 'exactly one declaration' \
    && _p "$L: pre-10.6: repair exits 0 and the live check sees one declaration" \
    || _f "$L: pre-10.6: repair failed" "rc=$rc out=$out"
  [ ! -e "$W/img" ] && _p "$L: pre-10.6: the image's file is disabled in the running container" \
    || _f "$L: pre-10.6: the image's file is still live" ""
  [ "$(_mlines)" = 1 ] && head -1 "$W/env" | cmp -s - "$W/env.orig" \
    && _p "$L: pre-10.6: the mask mount is recorded once, the install's line kept" \
    || _f "$L: pre-10.6: wp-run-extra.env wrong" "$(cat "$W/env")"
  _vols=$(env -i "$SH" -c '. "$1"; printf "%s" "$WP_EXTRA_VOLS"' _ "$W/env")
  case "$_vols" in
    *"/var/www/private:ro"*"-v $W/imask:/etc/apache2/conf-enabled/remoteip.conf:ro") _p "$L: pre-10.6: sourcing it gives both mounts" ;;
    *) _f "$L: pre-10.6: sourced WP_EXTRA_VOLS is wrong" "$_vols" ;;
  esac
  [ -f "$W/imask" ] && [ ! -s "$W/imask" ] && _p "$L: pre-10.6: the mask file exists and is empty" \
    || _f "$L: pre-10.6: no empty mask file" ""
  [ "$(_restarts)" = 1 ] && _p "$L: pre-10.6: WordPress restarted once" || _f "$L: pre-10.6: restart count $(_restarts)" ""

  rm -f "$W/restarts"; out=$(_fix); rc=$?
  [ "$rc" = 0 ] && printf '%s' "$out" | grep -q 'Nothing to repair' && [ "$(_restarts)" = 0 ] && [ "$(_mlines)" = 1 ] \
    && _p "$L: pre-10.6: a second run is a no-op (no restart, mount not added twice)" \
    || _f "$L: pre-10.6: not idempotent" "rc=$rc restarts=$(_restarts) lines=$(_mlines) out=$out"

  # The state the hand fix left on the field VM: mount recorded, image's file
  # removed in the container. Recognised as done.
  _reset; sed 's/^RemoteIPTrustedProxy /RemoteIPInternalProxy /' "$W/sec.orig" > "$W/wp-security.conf"
  printf '# masked: mod_remoteip is configured in conf-enabled/wp-security.conf\n' > "$W/remoteip.conf"
  printf "WP_EXTRA_VOLS='-v /home/wpuser/wp/secrets:/var/www/private:ro'\n" > "$W/env"
  printf 'WP_EXTRA_VOLS="${WP_EXTRA_VOLS} -v %s:/etc/apache2/conf-enabled/remoteip.conf:ro"\n' "$W/imask" >> "$W/env"
  out=$(_fix); rc=$?
  [ "$rc" = 0 ] && printf '%s' "$out" | grep -q 'Nothing to repair' && [ "$(_restarts)" = 0 ] \
    && _p "$L: pre-10.6: the field hand fix is recognised and left alone" \
    || _f "$L: pre-10.6: the field hand fix was not recognised" "rc=$rc out=$out"

  _pre106; echo fail > "$W/ct"; out=$(_fix); rc=$?
  [ "$rc" = 1 ] && cmp -s "$W/env" "$W/env.orig" && cmp -s "$W/img" "$W/img.orig" && [ ! -e "$W/imask" ] \
    && [ "$(_restarts)" = 0 ] \
    && _p "$L: pre-10.6: a failed configtest puts back the env file, the image's file, and restarts nothing" \
    || _f "$L: pre-10.6: a failed configtest left changes" "rc=$rc env=$(cat "$W/env") img=$([ -e "$W/img" ] && echo present || echo gone)"

  _pre106; : > "$W/rmfail"; out=$(_fix); rc=$?
  [ "$rc" = 1 ] && cmp -s "$W/env" "$W/env.orig" && [ ! -e "$W/imask" ] && [ "$(_restarts)" = 0 ] \
    && _p "$L: pre-10.6: if the image's file cannot be disabled, everything is put back" \
    || _f "$L: pre-10.6: a failed disable left changes" "rc=$rc"

  _pre106; rm -f "$W/env"; out=$(_fix); rc=$?
  [ "$rc" = 1 ] && [ ! -e "$W/env" ] && [ ! -e "$W/img" ] && printf '%s' "$out" | grep -q 'nothing records the mask' \
    && _p "$L: pre-10.6, no wp-run-extra.env: fixed now, not created blind, reported as not durable" \
    || _f "$L: pre-10.6, no env file: wrong handling" "rc=$rc out=$out"

  # Both problems at once: the 10.14 files AND the image's file.
  _reset; printf "WP_EXTRA_VOLS='-v /home/wpuser/wp/secrets:/var/www/private:ro'\n" > "$W/env"; rm -f "$W/imask"
  printf 'RemoteIPInternalProxy 10.0.0.0/8\n' > "$W/img"; cp "$W/img" "$W/img.orig"
  out=$(_fix); rc=$?
  [ "$rc" = 0 ] && grep -qx 'RemoteIPInternalProxy 10.20.10.10' "$W/wp-security.conf" && [ ! -e "$W/img" ] \
    && [ "$(_mlines)" = 1 ] && [ "$(_restarts)" = 1 ] \
    && _p "$L: a 10.4-shaped VM (old files and the image's file) is repaired in one run" \
    || _f "$L: a 10.4-shaped VM was not fully repaired" "rc=$rc out=$out"
}

_run_suite host /bin/sh "/usr/local/bin:/usr/bin:/bin"

if [ -n "$BB" ] && "$BB" --list >/dev/null 2>&1; then
  mkdir -p "$T/bb"; for _a in $("$BB" --list); do ln -sf "$BB" "$T/bb/$_a"; done
  _run_suite busybox "$T/bb/sh" "$T/bb"
else
  _f "BusyBox not found: the Alpine-shell pass did not run" "set BUSYBOX=/path/to/busybox"
fi

echo ""
echo "  remoteip-fix: ${PASS} passed, ${FAIL} failed"
[ "$FAIL" = 0 ]
